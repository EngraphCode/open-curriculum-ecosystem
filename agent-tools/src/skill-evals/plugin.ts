import { posix } from 'node:path';

import { err, ok, type Result } from '@oaknational/result';

import type { SkillSelection } from './args.js';
import { parseSkillEvalsFixture, parseTriggerValidation } from './fixture.js';
import type { ManifestFile } from './manifest.js';
import {
  projectSuite,
  type PluginSkill,
  type ProjectedFile,
  type ProjectionInput,
} from './project.js';
import type { SkillEvalsSeams } from './seams.js';

/**
 * The temporary plugin the runner is pointed at: its manifest, the
 * projection loaded from a skill's declared evals, and the version hashes
 * of what it carried. The skill directories themselves are composed in the
 * plugin-skill module.
 *
 * @packageDocumentation
 */

/** What loading a skill's declared evals needs. */
export interface LoadOptions extends SkillSelection {
  readonly repoRoot: string;
  /** Skills carried beside the one under evaluation. */
  readonly also: readonly SkillSelection[];
  readonly maxTurns: number;
  readonly triggerMaxTurns: number;
  readonly timeoutSeconds: number;
}

/** The projection and its files. */
export interface LoadedSuite {
  readonly projection: ProjectionInput;
  readonly files: readonly ProjectedFile[];
}

/** Previous runs' evidence under the canonical directory, left out of the version hashes. */
export const RESULTS_PREFIX = 'evals/results/';

/** The skill directory as a normalised POSIX path relative to the repository root: no `./`, no trailing `/`. */
function normalisedSkillDir(skill: string): string {
  const normalised = posix.normalize(skill.replaceAll('\\', '/'));
  return normalised.replace(/^\.\//u, '').replace(/\/+$/u, '');
}

/** The plugin skill a selection names; its canonical name is the directory's basename. */
function pluginSkillOf(selection: SkillSelection): PluginSkill {
  const canonicalRelativeDir = normalisedSkillDir(selection.skill);
  return {
    name: posix.basename(canonicalRelativeDir),
    hostSkill: selection.hostSkill,
    canonicalRelativeDir,
  };
}

/** The two fixture texts, the trigger file optional. */
function readFixtureTexts(
  canonicalSourceDir: string,
  seams: SkillEvalsSeams,
): Result<{ readonly fixture: string; readonly triggers: string | undefined }, Error> {
  const fixtureText = seams.readText(posix.join(canonicalSourceDir, 'evals', 'evals.json'));
  if (!fixtureText.ok) {
    return fixtureText;
  }
  if (fixtureText.value === undefined) {
    return err(
      new Error(`${canonicalSourceDir}/evals/evals.json is absent; the skill declares no evals`),
    );
  }
  const triggerText = seams.readText(
    posix.join(canonicalSourceDir, 'evals', 'trigger-validation.json'),
  );
  if (!triggerText.ok) {
    return triggerText;
  }
  return ok({ fixture: fixtureText.value, triggers: triggerText.value });
}

/** Read and validate the skill's declared evals, then project them. */
export function loadProjection(
  options: LoadOptions,
  seams: SkillEvalsSeams,
): Result<LoadedSuite, Error> {
  const skill = pluginSkillOf(options);
  const texts = readFixtureTexts(posix.join(options.repoRoot, skill.canonicalRelativeDir), seams);
  if (!texts.ok) {
    return texts;
  }
  const fixture = parseSkillEvalsFixture(texts.value.fixture);
  if (!fixture.ok) {
    return fixture;
  }
  const triggers =
    texts.value.triggers === undefined ? ok([]) : parseTriggerValidation(texts.value.triggers);
  if (!triggers.ok) {
    return triggers;
  }
  const projection: ProjectionInput = {
    fixture: fixture.value,
    triggers: triggers.value,
    skill,
    carried: options.also.map(pluginSkillOf),
    maxTurns: options.maxTurns,
    timeoutSeconds: options.timeoutSeconds,
    triggerMaxTurns: options.triggerMaxTurns,
  };
  const files = projectSuite(projection);
  return files.ok ? ok({ projection, files: files.value }) : files;
}

/** The plugin manifest the runner reads. */
export function pluginManifest(hostSkill: string): ProjectedFile {
  const manifest = {
    name: `${hostSkill}-evals`,
    version: '0.0.0',
    description: `Generated by agent-tools skill-evals: the ${hostSkill} adapter under evaluation`,
  };
  return {
    path: '.claude-plugin/plugin.json',
    content: `${JSON.stringify(manifest, null, 2)}\n`,
    executable: false,
  };
}

/** Write every file below `root`. */
export function writeAll(
  root: string,
  files: readonly ProjectedFile[],
  seams: SkillEvalsSeams,
): Result<void, Error> {
  for (const projected of files) {
    const written = seams.writeText(
      posix.join(root, projected.path),
      projected.content,
      projected.executable,
    );
    if (!written.ok) {
      return written;
    }
  }
  return ok(undefined);
}

/** Every regular file below `dir` with the blob id git gives it, paths under `exclude` left out. */
export function hashDirectory(
  dir: string,
  seams: SkillEvalsSeams,
  exclude: string,
): Result<readonly ManifestFile[], Error> {
  const listed = seams.listFiles(dir);
  if (!listed.ok) {
    return listed;
  }
  const paths = listed.value.filter((path) => !path.startsWith(exclude));
  const ids = seams.blobIds(dir, paths);
  if (!ids.ok) {
    return ids;
  }
  const { value } = ids;
  return value.length === paths.length
    ? ok(paths.map((path, index): ManifestFile => ({ path, blob: value[index] ?? '' })))
    : err(
        new Error(
          `blob ids for ${String(paths.length)} files in ${dir} came back as ${String(value.length)}`,
        ),
      );
}
